export function normalizeLocale(locale) {
  return Object.hasOwn(LOCALES, locale) ? locale : DEFAULT_LOCALE;
}

/** Dictionnaire complet d'une langue, avec repli sur le français. */
export function dictionary(locale) {
  const wanted = normalizeLocale(locale);
  return { ...DICTIONARY[DEFAULT_LOCALE], ...DICTIONARY[wanted] };
}

/** Vérifie qu'aucune clé ne manque dans une langue — utilisé par les tests. */
export function missingKeys() {
  const reference = Object.keys(DICTIONARY[DEFAULT_LOCALE]);
  const gaps = {};
  for (const [locale, entries] of Object.entries(DICTIONARY)) {
    const missing = reference.filter((key) => !Object.hasOwn(entries, key));
    if (missing.length) gaps[locale] = missing;
  }
  return gaps;
}
